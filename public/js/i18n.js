function applyLang(lang) {
    if (!LANG[lang]) return

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n')
        const text = LANG[lang][key]
        if (text) el.textContent = text
    })

    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang)
    })

    document.documentElement.lang = lang
    localStorage.setItem('lang', lang)
}

document.addEventListener('DOMContentLoaded', () => {
    const navIcons = document.querySelector('.nav-icons')
    if (navIcons) {
        const langSelector = document.createElement('div')
        langSelector.className = 'lang-selector'
        langSelector.innerHTML = ['es', 'en', 'fr', 'pt']
            .map(l => `<button class="lang-btn" data-lang="${l}">${l.toUpperCase()}</button>`)
            .join('')
        navIcons.appendChild(langSelector)

        langSelector.addEventListener('click', e => {
            if (e.target.classList.contains('lang-btn')) {
                applyLang(e.target.dataset.lang)
            }
        })
    }

    applyLang(localStorage.getItem('lang') || 'es')
})
